#!/usr/bin/env python3
"""Sync Claude Code rules, skills, subagents and MCP servers into Cline CLI.

Cline reads nothing from ~/.claude, so this bridges all four:
  1. ~/.cline/rules/AGENTS.md      ->  symlink to ~/.claude/CLAUDE.md
  2. ~/.cline/skills/<name>        ->  symlink to ~/.claude/skills/<name>
  3. ~/.claude/agents/*.md         ->  ~/.cline/agents/*.yaml (Cline only loads .yml/.yaml)
  4. mcpServers in ~/.claude.json  ->  ~/.cline/data/settings/cline_mcp_settings.json

Claude stays the source of truth. Safe to rerun; it only writes what changed.
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

import yaml

HOME = Path.home()
CLAUDE_DIR = HOME / ".claude"
CLAUDE_RULES = CLAUDE_DIR / "CLAUDE.md"
CLAUDE_SKILLS = CLAUDE_DIR / "skills"
CLAUDE_AGENTS = CLAUDE_DIR / "agents"
CLAUDE_JSON = HOME / ".claude.json"

CLINE_DIR = HOME / ".cline"
CLINE_RULES = CLINE_DIR / "rules" / "AGENTS.md"
CLINE_SKILLS = CLINE_DIR / "skills"
CLINE_AGENTS = CLINE_DIR / "agents"
CLINE_MCP = CLINE_DIR / "data" / "settings" / "cline_mcp_settings.json"

MARKER = "# generated by claude-cline-sync from ~/.claude/agents/{name}.md, edit the source instead"
MARKER_PREFIX = "# generated by claude-cline-sync"


class BlockDumper(yaml.SafeDumper):
    pass


def _str_representer(dumper, value):
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


BlockDumper.add_representer(str, _str_representer)


def log(msg, quiet=False):
    if not quiet:
        print(msg)


def warn(msg):
    print(f"warning: {msg}", file=sys.stderr)


def split_frontmatter(text):
    if not text.startswith("---"):
        return None, text
    end = text.find("\n---", 3)
    if end < 0:
        return None, text
    fm = yaml.safe_load(text[3:end]) or {}
    body = text[end + 4:].lstrip("\n")
    return fm, body


def ensure_symlink(link, target, dry_run, quiet):
    """Point link at target. Returns 1 if it changed, 0 otherwise."""
    if link.is_symlink() and link.resolve() == target.resolve():
        return 0
    if link.exists() or link.is_symlink():
        warn(f"{link} exists and is not a symlink to {target}, left alone")
        return 0
    log(f"{'would link' if dry_run else 'linked'} {link} -> {target}", quiet)
    if not dry_run:
        link.parent.mkdir(parents=True, exist_ok=True)
        link.symlink_to(target)
    return 1


def sync_rules(dry_run, quiet):
    # Cline lists rule files with dirent.isFile(), which skips symlinks, but it
    # stats AGENTS.md by name, so a symlink with that exact name is picked up.
    if not CLAUDE_RULES.exists():
        return 0
    return ensure_symlink(CLINE_RULES, CLAUDE_RULES, dry_run, quiet)


def sync_skills(dry_run, quiet):
    # One link per skill instead of linking the whole directory, so skills
    # installed through Cline land in ~/.cline/skills, not in ~/.claude/skills.
    changed = 0
    wanted = set()
    for src in sorted(CLAUDE_SKILLS.iterdir()) if CLAUDE_SKILLS.is_dir() else []:
        if not (src / "SKILL.md").is_file():
            continue
        wanted.add(src.name)
        changed += ensure_symlink(CLINE_SKILLS / src.name, src, dry_run, quiet)

    for link in sorted(CLINE_SKILLS.iterdir()) if CLINE_SKILLS.is_dir() else []:
        if link.name in wanted or not link.is_symlink():
            continue
        target = Path(link.readlink())
        if not target.is_absolute():
            target = link.parent / target
        if CLAUDE_SKILLS not in target.parents:
            continue
        log(f"{'would remove' if dry_run else 'removed'} stale skill link {link.name}", quiet)
        if not dry_run:
            link.unlink()
        changed += 1
    return changed


def convert_agent(src):
    fm, body = split_frontmatter(src.read_text())
    if fm is None or not fm.get("description"):
        warn(f"{src.name}: no frontmatter description, skipped")
        return None

    out = {"name": fm.get("name") or src.stem, "description": fm["description"]}

    model = fm.get("model")
    if model and model != "inherit":
        warn(f"{src.name}: model {model!r} has no Cline equivalent, using default")
    if fm.get("tools"):
        warn(f"{src.name}: tools list not converted, agent gets Cline defaults")

    header = yaml.dump(out, Dumper=BlockDumper, sort_keys=False, allow_unicode=True, width=10**9)
    return f"---\n{MARKER.format(name=src.stem)}\n{header}---\n\n{body}"


def sync_agents(dry_run, quiet):
    changed = 0
    wanted = set()
    if not dry_run:
        CLINE_AGENTS.mkdir(parents=True, exist_ok=True)

    for src in sorted(CLAUDE_AGENTS.glob("*.md")):
        content = convert_agent(src)
        if content is None:
            continue
        dst = CLINE_AGENTS / f"{src.stem}.yaml"
        wanted.add(dst.name)
        if dst.exists() and dst.read_text() == content:
            continue
        if dst.exists() and MARKER_PREFIX not in dst.read_text():
            warn(f"{dst} exists and was not generated by this script, left alone")
            continue
        log(f"{'would write' if dry_run else 'wrote'} agent {dst.name}", quiet)
        if not dry_run:
            dst.write_text(content)
        changed += 1

    if CLINE_AGENTS.is_dir():
        for dst in sorted(CLINE_AGENTS.glob("*.yaml")):
            if dst.name in wanted or MARKER_PREFIX not in dst.read_text():
                continue
            log(f"{'would remove' if dry_run else 'removed'} stale agent {dst.name}", quiet)
            if not dry_run:
                dst.unlink()
            changed += 1
    return changed


def sync_mcp(dry_run, quiet):
    if not CLAUDE_JSON.exists():
        return 0
    servers = json.loads(CLAUDE_JSON.read_text()).get("mcpServers") or {}
    if not servers:
        return 0

    # Cline does a locked read-modify-write on this file; don't race it.
    if any(CLINE_MCP.parent.glob(CLINE_MCP.name + "*.lock")):
        warn(f"{CLINE_MCP} is locked by Cline, MCP sync skipped this time")
        return 0

    settings = json.loads(CLINE_MCP.read_text()) if CLINE_MCP.exists() else {}
    current = settings.setdefault("mcpServers", {})

    changed = 0
    for name, server in servers.items():
        # Cline accepts Claude's server entry format as is.
        if current.get(name) == server:
            continue
        log(f"{'would set' if dry_run else 'set'} mcp server {name}", quiet)
        current[name] = server
        changed += 1

    if changed and not dry_run:
        if CLINE_MCP.exists():
            shutil.copy2(CLINE_MCP, CLINE_MCP.with_suffix(".json.bak"))
        CLINE_MCP.parent.mkdir(parents=True, exist_ok=True)
        CLINE_MCP.write_text(json.dumps(settings, indent=2, ensure_ascii=False) + "\n")
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true", help="show changes without writing")
    parser.add_argument("--quiet", action="store_true", help="print nothing unless something changed or failed")
    args = parser.parse_args()

    changed = (
        sync_rules(args.dry_run, args.quiet)
        + sync_skills(args.dry_run, args.quiet)
        + sync_agents(args.dry_run, args.quiet)
        + sync_mcp(args.dry_run, args.quiet)
    )
    if changed == 0:
        log("already in sync", args.quiet)
    elif args.quiet:
        print(f"claude-cline-sync: {changed} change(s) applied")


if __name__ == "__main__":
    main()
